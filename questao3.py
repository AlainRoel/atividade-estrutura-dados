# Questão 3 -  Considere o vetor:
vetor = [10, 20, 30, 40, 50]

print("Vetores: ", vetor)

# a)
print("Qual valor será exibido ao executar vetor[0]?", vetor[0])  # 10

# b)
print("Qual valor será exibido ao executar vetor[3]?", vetor[3])  # 40

# c) Explicação:
# Em Python, a indexação começa em 0 porque o índice representa
# o deslocamento do elemento em relação ao início da lista.
# Isso facilita operações internas, como percorrer estruturas de dados
# e realizar cálculos de posição de forma mais eficiente.
