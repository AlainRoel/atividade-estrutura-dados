# Questão 4 -  Considere a matriz a seguir:
matriz = [
    [2, 4, 6],
    [8, 10, 12],
    [14, 16, 18]
]

print("Matriz:", matriz)

# a) Valor acessado por matriz[0][2]
print("a) Qual valor é acessado por matriz[0][2]?", matriz[0][2])  # 6

# b) Valor acessado por matriz[2][1]
print("b) Qual valor é acessado por matriz[2][1]?", matriz[2][1])  # 16

# c) Explicação:
# Em matrizes, o primeiro índice representa a linha e o segundo
# representa a coluna. Dessa forma, matriz[linha][coluna] permite
# acessar um valor específico dentro da estrutura bidimensional.
